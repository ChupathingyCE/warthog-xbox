#!/usr/bin/env python3
"""Sources the Xbox build (port/xbox/build.py) takes from the Linux port's.

    xbox_sources.py common chupathingyce/port/linux/src/halo_linker_common.c OUT
        The pooled COMMON globals (every HALO_COMMON line), as plain zeroed
        definitions: the Xbox link has no weak symbols to fall back on, and
        nothing else defines them.
    xbox_sources.py bink chupathingyce/port/linux/src/bink_null.c OUT
        The Bink stub, with the SDK's headers in place of the Linux
        platform layer's.
    xbox_sources.py copy chupathingyce/port/linux/src/p2p.c OUT
        A source as it is (internet play's, and its libraries'), in a folder
        of the build's, so that its quoted includes find port/xbox/p2p's
        headers (named on the command line) before the Linux layer's beside
        it. Its lines keep their file and numbers (#line).
"""

import argparse
import re
from pathlib import Path

# what the stub uses of the Linux platform layer
PLATFORM = """#include <xtl.h>

ULONG __cdecl DbgPrint(PCSTR format, ...);
#define platform_log(format, ...) DbgPrint(format "\\n", ##__VA_ARGS__)"""

HEADER = "/* generated by tools/xbox_sources.py from {source}; do not edit */\n\n"


def common(source: Path) -> str:
    # (the console builds Custom Edition maps: that branch's sizes, not the #else's)
    lines = []
    custom_edition = other = False
    for line in source.read_text(encoding="utf-8").splitlines():
        if line.startswith("#ifdef HALO_CUSTOM_EDITION"):
            custom_edition = True
        elif custom_edition and line.startswith("#else"):
            other = True
        elif custom_edition and line.startswith("#endif"):
            custom_edition = other = False
        elif not other and re.match(r"HALO_COMMON\(\w+, *\d+( *\+ *\d+)?\);", line):
            lines.append(line)
    if not lines:
        raise SystemExit(f"{source}: no HALO_COMMON definitions")
    return (HEADER.format(source=source.as_posix())
            + "#define HALO_COMMON(name, size) __declspec(align(16)) unsigned char name[size]\n\n"
            + "\n".join(lines) + "\n")


def bink(source: Path) -> str:
    text = source.read_text(encoding="utf-8")
    if '#include "platform.h"' not in text:
        raise SystemExit(f"{source}: its platform.h include moved")
    return HEADER.format(source=source.as_posix()) + text.replace('#include "platform.h"', PLATFORM)


def copy(source: Path) -> str:
    return HEADER.format(source=source.as_posix()) + f'#line 1 "{source.as_posix()}"\n' + source.read_text(encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("kind", choices=("common", "bink", "copy"))
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    text = {"common": common, "bink": bink, "copy": copy}[args.kind](args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.is_file() or args.output.read_text(encoding="utf-8") != text:
        args.output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
